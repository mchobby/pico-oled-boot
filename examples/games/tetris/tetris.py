# Grid is game board boolean. grid[10][18]
grid = [] # Game board
for i in range(10):
	grid.append( [0]*18 )


def copy_piece( target_piece, selected_type, rotation):
	# target_piece  : where the current_type mist be copied
	# selected_type : from 0..5 (index in PIECES)
	# rotation      : current rotation of the piece to copy (from 0 to 3)
	for xy in range(2): 
		target_piece[xy] = PIECES[selected_type][rotation][xy] # This is a copy of reference


def draw_next_piece():
	global next_type 
	for idot in range(4): # 4 dot to draw
		display.fill_rect( 50 + 3*PIECES[next_type][0][0][idot], 4 + 3*PIECES[next_type][0][1][idot], 2, 2, 1 )


def draw_layout():
	display.line( 0, 15, GAME_WIDTH, 15, 1)
	display.rect( 0, 0, GAME_WIDTH, GAME_HEIGHT, 1)
	if next_type != None:
		draw_next_piece()
	display.text( str(score), 7, 4 )


def draw_grid():
	for x in range( 10 ):
		for y in range( 18 ):
			if grid[x][y]:
				display.fill_rect( MARGIN_LEFT + (SIZE + 1)*x, MARGIN_TOP + (SIZE + 1)*y, SIZE, SIZE, 1 )


def draw_piece( current_type, rotation, piece_x, piece_y ):
	for i in range( 4 ):
		display.fill_rect(MARGIN_LEFT + (SIZE + 1)*(piece_x + piece[0][i]), MARGIN_TOP + (SIZE + 1)*(piece_y + piece[1][i]), SIZE, SIZE, 1)


def generate():
	global current_type, next_type, piece_x, piece_y, rotation
	current_type = next_type
	next_type    = random.randint(0,TYPES_COUNT-1)
	if current_type != 5:
		piece_x = random.randint(0,8) # 0..8
	else:
		piece_x = random.randint(0,6) # 0..6
	piece_y = 0
	rotation = 0
	copy_piece(piece, current_type, rotation)


def remove_line( line ):
	# Remove/break the complete line from the pit
	# Make lines above it drop down 
	global grid, score
	y = line
	while y>=0:
		for x in range( 10 ):
			grid[x][y] = grid[x][y-1]
		y -= 1
	
	for x in range( 10 ):
		grid[x][0] = 0
	
	#display.invertDisplay(true);
	#delay(50);
	#display.invertDisplay(false);
	score += 10


def drop_lines():
	# Browse all lines and drop lines that are completes
	global grid
	full = False
	y = 17
	while y >= 0:
		full = True
		for x in range(10):
			full = full and (grid[x][y]==1)
		
		if full:
			remove_line(y)
			y += 1
		y -= 1


def is_full():
	# Check if a block reached the top of game board
	return any( [grid[x][0]==1 for x in range(10)] )

def refresh():
	display.fill(0)
	draw_layout()
	draw_grid()
	draw_piece( current_type, 0, piece_x, piece_y )
	display.show()


def next_collision():
	for i in range(4):
		x = piece_x + piece[0][i]
		y = piece_y + piece[1][i] + 1
		
		if(y > 17) or (grid[x][y]==1):
		  return True	
	return False


def next_horizontal_collision( piece, direction ):
	# direction : +1 or -1 or 0 (to test after rotation)
	for i in range(4):
		new_x = piece_x + piece[0][i] + direction
		new_y = piece_y + piece[1][i]
		if new_y>=18: # Rotate to close of the bottom
			return True
		if (new_x>9) or (new_x<0) or ((grid[new_x][new_y])==1):
			return True

	return False


def get_max_rotation(current_type):
	return len(PIECES[current_type])


def can_rotate( rotation ):
	global temp_piece 	
	copy_piece( temp_piece, current_type, rotation )
	return not( next_horizontal_collision( temp_piece, 0 ) )


def draw_intro():
	global display, next_type, timer
	# draw bitmap doesn't rotate!!!
	fbtls.draw_bitmap( 0, 0, MANTEX_LOGO, 64, 82, 1 )
	display.text( 'Tetris', 8, 68, 0 )
	display.text( 'for', 20, 90 )
	display.text( 'Micro', 12, 100 )
	display.text( 'Python',7, 110 )
	display.rect( 0, 0, GAME_WIDTH, GAME_HEIGHT, 1)
	display.show()
	while not display.any_key_pressed:
		time.sleep_ms(50)

def init_game():
	global next_type, timer, score, grid
	display.fill(0)
	draw_layout()
	display.show()

	next_type = random.randint(0,TYPES_COUNT-1)
	score = 0
	# Reset the grid (game board)
	for x in range(len(grid)):
		for y in range(len(grid[x])):
			grid[x][y]=0
	generate()
	timer = time.ticks_ms()


def draw_score():
	global score
	display.fill( 0 )
	display.fill_rect( 5, (GAME_HEIGHT//2)-20, GAME_WIDTH-10, 40, 1 )
	display.rect( 7, (GAME_HEIGHT//2)-20+3, GAME_WIDTH-14, 40-6, 0)
	display.text( "Score", (GAME_WIDTH-5*8)//2, (GAME_HEIGHT//2)-10, 0 )
	s = str(score)
	display.text( s, (GAME_WIDTH-len(s)*8)//2, (GAME_HEIGHT//2)+5, 0 )
	display.show()
	time.sleep(1)
	while not display.any_key_pressed:
		time.sleep_ms(10)


def game_loop():
	global timer,piece_x,piece_y,rotation, current_type, interval
	last_dir = 0
	last_dir_time = time.ticks_ms()
	last_rotate_time = time.ticks_ms()
	while True:
		if time.ticks_diff( time.ticks_ms(), timer ) > interval:	
			drop_lines() # Complete line should disappearts
			refresh()

			if next_collision():
				for idot in range( 4 ):
					grid[ piece_x + piece[0][idot] ][ piece_y + piece[1][idot] ] = 1
				generate()
			else:
				piece_y += 1
			  
			timer = time.ticks_ms()


		if is_full():
			return

		# Remind: we physically rotated the screen 
		dir = display.dir 
		if (dir==last_dir) and (time.ticks_diff(time.ticks_ms(),last_dir_time)<KEY_REPEAT_INTERVAL ):
			continue
		last_dir = dir
		last_dir_time = time.ticks_ms()

		if dir==DOWN: # go Left 
			if not next_horizontal_collision(piece, -1):
				piece_x -= 1
				refresh()


		if dir==UP: # go Right			
			if not next_horizontal_collision( piece, 1 ):
				piece_x += 1
				refresh()


		if dir==RIGHT: # go Down
			interval = 20
		else:
			interval = 400
		

		if dir==START: # Rotate Piexe
			if time.ticks_diff( time.ticks_ms(), last_rotate_time ) < ROTATE_REPEAT_INTERVAL:
				continue
			last_rotate_time = time.ticks_ms()

			if ( rotation==(get_max_rotation(current_type)-1) ) and  can_rotate(0):
				rotation = 0
			elif can_rotate(rotation + 1):
				rotation += 1
			copy_piece( piece, current_type, rotation )
			refresh()
		


# === Main Loop ===
draw_intro()
while True:
	init_game()
	game_loop()
	draw_score()
	
  

